#!/usr/bin/env bash
# Compare a temporary generation without rewriting the working tree.
set -euo pipefail
cd "$(dirname "$0")/.."
sample_generated_dir=$(mktemp -d /tmp/catalog-sqlc.XXXXXXXX)
trap 'rm -rf -- "$sample_generated_dir"' EXIT
cp sqlc.yaml "$sample_generated_dir/sqlc.yaml"
cp -R db "$sample_generated_dir/db"
sqlc generate -f "$sample_generated_dir/sqlc.yaml"

while IFS= read -r -d '' sample_generated; do
  sample_relative=${sample_generated#"$sample_generated_dir/"}
  if ! diff -u "$sample_relative" "$sample_generated"; then
    echo "Generated queries differ; run make generate." >&2
    exit 1
  fi
done < <(find "$sample_generated_dir/internal/db" -name '*.go' -type f -print0)
while IFS= read -r -d '' sample_current; do
  if grep -q '^// Code generated by sqlc. DO NOT EDIT.' "$sample_current"; then
    if [[ ! -f "$sample_generated_dir/$sample_current" ]]; then
      echo "Stale generated file: $sample_current" >&2
      exit 1
    fi
  fi
done < <(find internal/db -name '*.go' -type f -print0)
